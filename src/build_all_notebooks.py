                "## 4. Time-Domain Filtering Theory: Causal Delay vs. Zero-Phase Bidirectional Filtering\n",
                "\n",
                "### Causal Phase Distortion & Group Delay:\n",
                "- A causal IIR filter processes samples strictly forward in time: $y[n] = \\sum_{k=0}^2 b_k x[n-k] - \\sum_{k=1}^2 a_k y[n-k]$.\n",
                "- Because causal IIR filters have non-linear phase, they introduce frequency-dependent group delay:\n",
                "  $$\\tau_g(\\omega) = -\\frac{d\\phi(\\omega)}{d\\omega}$$\n",
                "- In our 4th-order Butterworth design, the passband group delay is $\\tau_g \\approx 16.5 - 24.3\\,\\text{ms}$ ($\\approx 8 - 12$ samples at $500\\,\\text{Hz}$, settling at $\\approx 17.9\\,\\text{ms}$ at $10\\,\\text{Hz}$, as demonstrated in Figure 2C). While suitable for live edge streaming, this delay introduces phase distortion that lags jump takeoff transitions and landing shocks in post-flight analytics.\n",
                "\n",
                "### Zero-Phase Bidirectional Filtering (`filtfilt_sos`):\n",
                "- For post-session telemetry analytics, flight segment isolation, and landing energy computation, we implement zero-phase filtering:\n",
                "  1. Forward pass through SOS filter: $y_{\\text{fwd}}[n] = \\mathcal{H}\\{x[n]\\}$.\n",
                "  2. Time reversal: $y_{\\text{rev}}[n] = y_{\\text{fwd}}[-n]$.\n",
                "  3. Backward pass through identical SOS filter: $y_{\\text{rev2}}[n] = \\mathcal{H}\\{y_{\\text{rev}}[n]\\}$.\n",
                "  4. Final time reversal: $y_{\\text{final}}[n] = y_{\\text{rev2}}[-n]$.\n",
                "- **Zero Phase Shift**: The forward phase shift $+\\phi(\\omega)$ is perfectly cancelled by the backward phase shift $-\\phi(\\omega)$, yielding:\n",
                "  $$\\angle H_{\\text{filtfilt}}(e^{j\\omega}) \\equiv 0^\\circ \\implies \\tau_g = 0.0\\,\\text{ms}$$\n",
