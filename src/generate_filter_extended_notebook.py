            "        P = np.eye(5) * 1.0\n",
            "        for _ in range(max_iter):\n",
            "            P_pred = self.F @ P @ self.F.T + self.Q\n",
            "            S = float(self.H @ P_pred @ self.H) + self.R\n",
            "            K = (P_pred @ self.H) / S\n",
            "            P_new = P_pred - np.outer(K, self.H @ P_pred)\n",
            "            if np.max(np.abs(P_new - P)) < tol:\n",
            "                break\n",
            "            P = P_new\n",
            "        return K, P\n",
